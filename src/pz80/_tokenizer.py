#!/usr/bin/env python3

"""アセンブラの字句解析。

ソース文字列をトークン列へ分解する。状態を持たず、他のモジュールにも依存しない
（`asm.py` の 4 責務のうち、唯一完全に独立している層）。

**1 本の正規表現による 1 パス走査**で実装している。`re.finditer` が先頭から
重ならないマッチを順に返すので、`SCAN` の選択肢を並べた順がそのまま
**字句の優先順位**になる。

以前は「1文字トークンを `str.replace` で空白で囲んでから空白で分割する」方式で、
それに伴う退避・復元（`__STRING_LITERAL_n__` / `__OPERATOR_n__`）を持っていた。
経緯と、その方式が抱えていた問題は `docs/tokenizer-scan-migration.md` を参照。
"""

import re

# --------------------------------------------------------------------------
# 走査に使う定数
#
# 大文字は Python の定数、小文字（`string` / `comment` / `op2` / `op1` / `word`）は
# 正規表現のグループ名。両者は 1 対 1 ではなく、SINGLE_CHAR_TOKENS は
# op1（区切る側）と word（区切られる側の否定クラス）の両方で使う。
# --------------------------------------------------------------------------

# 1文字の区切り・演算子。`;` はコメント開始なので別扱いにする。
SINGLE_CHAR_TOKENS = "():,+-*/$&|^~%<>!"

# 2文字演算子。1文字より必ず先に試す必要がある（後述）。
TWO_CHAR_OPS = ["<<", ">>", "<=", ">=", "==", "!=", "&&", "||"]

# **2文字演算子に使う文字は、すべて語の境界でなければならない。**
# そうでないと `word` が `A==4` を丸ごと 1 語として飲み込み、`op2` に到達しない
# （`word` は先に始まった位置から貪欲に伸びるため、後ろに `op2` を置いても届かない）。
#
# 置換方式ではこの条件が要らなかった。`re.sub` が位置に関係なく全文の `==` を
# 先に退避していたためで、走査方式にして初めて表面化した不変条件である。
# 実際 `=` が SINGLE_CHAR_TOKENS から漏れていた（`=` は単独では演算子ではなく、
# `==` `!=` `<=` `>=` の部品としてしか現れないため気づきにくい）。
#
# 集合演算で導くので、TWO_CHAR_OPS に演算子を足しても自動的に追従する。
_EXTRA_DELIMS = "".join(sorted(set("".join(TWO_CHAR_OPS)) - set(SINGLE_CHAR_TOKENS)))

# op1（区切る側）と word（区切られる側の否定クラス）の両方が使う区切り文字集合。
DELIMITERS = SINGLE_CHAR_TOKENS + _EXTRA_DELIMS

# 文字列リテラル。ダブルクォート版とシングルクォート版の 2 択。
#
#   \"(?:\\.|[^\"\\])*\"        ダブルクォート版
#   '(?:\\.|[^'\\])*'           シングルクォート版
#
#   (?:...)   グループ化するがキャプチャしない
#   \\.       バックスラッシュ + 任意の 1 文字。エスケープを 1 単位として飲み込む
#   [^"\\]    クォートでもバックスラッシュでもない普通の文字
#
# `\\.` を先に置くのが肝で、`"a\"b"` の `\"` が 1 単位で消費されるため
# **エスケープされたクォートで文字列が終わらない**。
#
# raw 文字列なのでソース上の `\"` は正規表現エンジンにも `\"` として渡る。
# `"` は正規表現のメタ文字ではないのでこのバックスラッシュは無くても動くが、
# `r"..."` の中に `"` を書く都合で付いている。
STRING_PATTERN = r"\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'"

# --------------------------------------------------------------------------
# 走査器
#
# 5 つの選択肢を `|` で並べ、それぞれに名前付きグループを付ける。
# Python の `|` は**左から試して最初に成功したものを採用する**（最長一致ではなく
# 先着順）。この性質がそのまま優先順位になるので、**並べる順が仕様**である。
#
# 1. string  — 最優先。中の `;` や演算子を他の選択肢に見せないため。
#              `db "a;b"` なら `"a;b"` が丸ごと 1 トークンとして消費される。
#              STRING_PATTERN 自体がトップレベルに `|` を含む 2 択なので、
#              `(?P<string>` … `)` で**必ず囲む**。囲まないと外側の選択肢と
#              同じ階層にほどけ、`lastgroup` が名前を返さなくなる。
#
# 2. comment — `;` から行末まで（`.` は改行以外の任意文字）。1 行ずつ処理する前提。
#              **string より後ろに置くこと。** 逆順だと `db "a;b"` の `;` が
#              コメント開始と誤認される。
#
# 3. op2     — 2文字演算子。**op1 より必ず先。** `A<<2` を走査するとき、
#              op2 が先なら `['A', '<<', '2']`、op1 が先だと `<` に一致して
#              `['A', '<', '<', '2']` に割れる。`&&`/`&`、`||`/`|` も同じ関係。
#              re.escape が `|` を `\|` にするので、`\|\|` がリテラルの `||` を表す。
#
# 4. op1     — 1文字の区切り・演算子。文字クラスなのでこのうち 1 文字に一致。
#
# 5. word    — それ以外の語。否定の文字クラスで「空白でも区切り文字でも `;` でもない
#              文字」の 1 文字以上の連続。`\s` と `;` を含めることで**空白と区切り
#              文字が語の境界になる**ため、`str.split()` による分割が要らない。
#
# 4 と 5 が同じ DELIMITERS から作られている点が重要で、区切る側と区切られる側が
# 1 箇所の定義に自動的に追従する。escape は re.escape に任せる
# （手で書くと `&` や `~` が対象であることを見落とす）。
# --------------------------------------------------------------------------

_SCAN = re.compile(
    "(?P<string>" + STRING_PATTERN + ")"
    "|(?P<comment>;.*)"
    "|(?P<op2>" + "|".join(re.escape(o) for o in TWO_CHAR_OPS) + ")"
    "|(?P<op1>[" + re.escape(DELIMITERS) + "])"
    r"|(?P<word>[^\s" + re.escape(DELIMITERS + ";") + "]+)"
)


def tokenize(src):
    """ソースコード1行をトークンリストに変換します。

       トークンリスト例 : ['ld', '(', 'hl', ')', ',', 'a'] ※コメント文字 ";" 以降の要素は削除する
       文字列リテラル （"..." または '...'） は1つのトークンとして扱う

    `_SCAN` で 1 回走査するだけで、コメント除去も分割も同時に済みます。
    `lastgroup` が `"comment"` になった時点で打ち切るため、コメント除去という
    前処理工程を持ちません。

    空白は `_SCAN` のどの選択肢にも一致しないので、走査から自然に脱落します
    （明示的に読み飛ばす必要がありません）。

    Args:
        src (str): ソース文字列 (例: "ld a, 0x10 ; コメント")

    Returns:
        list: トークンリスト (例: ["ld", "a", ",", "0x10"])
    """
    tokens = []
    for m in _SCAN.finditer(src):
        if m.lastgroup == "comment":
            break
        tokens.append(m.group(0))
    return tokens


def source(lines, file=None):
    """アセンブラソースからアセンブルリストを生成します。

    Args:
        lines (list): アセンブラソースの行リスト
                      例: ["org 0x100\\n", "ld a, 0x10\\n"]
        file (str, optional): ソース識別子。各 item の "file" フィールドに付与される。

    Returns:
        list: トークン化されたアセンブルリスト。1行を辞書形式でまとめて全体をリスト化。
              空行は除外される。
              例: [{"line": 1, "file": "main.asm", "asm": ["org", "0x100"]},
                   {"line": 2, "file": "main.asm", "asm": ["ld", "a", ",", "0x10"]}]
    """
    result = []
    for line_num, line in enumerate(lines, 1):
        tokens = tokenize(line)
        if tokens:
            result.append({"line": line_num, "file": file, "asm": tokens})
    return result
